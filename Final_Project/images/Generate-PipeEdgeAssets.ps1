param(
    [string]$Source = (Join-Path $PSScriptRoot 'pipeEdge.png')
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$bitmap = [System.Drawing.Bitmap]::new((Resolve-Path -LiteralPath $Source).Path)
$preview = [System.Drawing.Bitmap]::new(64, 16)
try {
    if ($bitmap.Width -ne 64 -or $bitmap.Height -ne 16) {
        throw 'The pipe cap must be exactly 64 x 16 pixels.'
    }

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add(('-- {0}: 64 x 16 bottom cap, row-major, RRRGGGBB, opaque.' -f [System.IO.Path]::GetFileName($Source)))
    $lines.Add('-- Top cap reuses this image with source row = 15 - local row.')
    $lines.Add('-- Generated by images/Generate-PipeEdgeAssets.ps1.')
    $lines.Add('DEPTH = 1024;')
    $lines.Add('WIDTH = 8;')
    $lines.Add('ADDRESS_RADIX = HEX;')
    $lines.Add('DATA_RADIX = HEX;')
    $lines.Add('CONTENT BEGIN')
    for ($y = 0; $y -lt 16; $y++) {
        for ($x = 0; $x -lt 64; $x++) {
            $color = $bitmap.GetPixel($x, $y)
            if ($color.A -ne 255) {
                throw 'The pipe cap must be fully opaque.'
            }
            $red = $color.R -shr 5
            $green = $color.G -shr 5
            $blue = $color.B -shr 6
            $value = ($red -shl 5) -bor ($green -shl 2) -bor $blue
            $lines.Add(('{0:X3}: {1:X2};' -f ($y * 64 + $x), $value))
            $preview.SetPixel($x, $y, [System.Drawing.Color]::FromArgb(
                [int][Math]::Round($red * 255 / 7),
                [int][Math]::Round($green * 255 / 7),
                [int][Math]::Round($blue * 255 / 3)))
        }
    }
    $lines.Add('END;')
    $projectRoot = Split-Path -Parent $PSScriptRoot
    $mifPath = Join-Path $projectRoot 'ProjectFiles/FlappyBird/RTL/pipeEdge.mif'
    [System.IO.File]::WriteAllLines($mifPath, $lines, [System.Text.Encoding]::ASCII)
    $bitmap.Save((Join-Path $PSScriptRoot 'pipeEdge.bmp'), [System.Drawing.Imaging.ImageFormat]::Bmp)
    $preview.Save((Join-Path $PSScriptRoot 'pipeEdge_RGB332.png'), [System.Drawing.Imaging.ImageFormat]::Png)
    Write-Output 'Generated pipeEdge.mif (1024 x 8 bits), pipeEdge.bmp, and pipeEdge_RGB332.png.'
}
finally {
    $preview.Dispose()
    $bitmap.Dispose()
}
