param([string]$Icons = (Join-Path $PSScriptRoot 'icons.png'))
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.Drawing
$root=Split-Path -Parent $PSScriptRoot
$tileCount=4
$depth=1024*$tileCount
$reference=Join-Path $root 'work/hearts'
[void](New-Item -ItemType Directory -Path $reference -Force)
$bitmap=[System.Drawing.Bitmap]::new((Resolve-Path -LiteralPath $Icons).Path)
try {
    if($bitmap.Width -ne (32*$tileCount) -or $bitmap.Height -ne 32){throw 'icons.png must be 128x32: coin, heart, TNT, ghost.'}
    $pixels=[int[]]::new($depth)
    for($tile=0;$tile -lt $tileCount;$tile++){for($y=0;$y -lt 32;$y++){for($x=0;$x -lt 32;$x++){
        $color=$bitmap.GetPixel(($tile*32+$x),$y)
        if($color.A -ne 0 -and $color.A -ne 255){throw 'Use binary alpha without antialiasing.'}
        $pixels[$tile*1024+$y*32+$x]=if($color.A -eq 0){-1}else{(($color.R -shr 5) -shl 5) -bor (($color.G -shr 5) -shl 2) -bor ($color.B -shr 6)}
    }}}
    $colors=@($pixels | Where-Object {$_ -ge 0} | Sort-Object -Unique)
    if($colors.Count -gt 15){throw 'At most 15 RGB332 colors plus transparency are supported.'}
    $palette=@{}
    for($i=0;$i -lt $colors.Count;$i++){$palette[$colors[$i]]=$i+1}
    $lines=[Collections.Generic.List[string]]::new()
    $lines.Add('-- icons.png: coin, heart, TNT, ghost; 32x32 tile-major, index 0 transparent.')
    $lines.Add('-- Generated by images/Generate-PickupAssets.ps1; opaque white is preserved.')
    foreach($line in @("DEPTH = $depth;",'WIDTH = 4;','ADDRESS_RADIX = HEX;','DATA_RADIX = HEX;','CONTENT BEGIN')){$lines.Add($line)}
    $referencePixels=[Collections.Generic.List[string]]::new()
    for($address=0;$address -lt $depth;$address++){
        $index=if($pixels[$address] -lt 0){0}else{$palette[$pixels[$address]]}
        $lines.Add(('{0:X3}: {1:X1};' -f $address,$index))
        $referencePixels.Add(('{0:X3}' -f $(if($pixels[$address] -lt 0){0}else{256 -bor $pixels[$address]})))
    }
    $lines.Add('END;')
    [IO.File]::WriteAllLines((Join-Path $root 'ProjectFiles/FlappyBird/RTL/pickups.mif'),$lines,[Text.Encoding]::ASCII)
    [IO.File]::WriteAllLines((Join-Path $reference 'icons.hex'),$referencePixels,[Text.Encoding]::ASCII)
    $block=[Collections.Generic.List[string]]::new()
    $block.Add('// BEGIN GENERATED PALETTE')
    $block.Add('always_comb begin')
    $block.Add('    case (colorIndex)')
    for($i=0;$i -lt $colors.Count;$i++){$block.Add(("        4'd{0}: pixelRGB = 8'h{1:X2};" -f ($i+1),$colors[$i]))}
    $block.Add("        default: pixelRGB = 8'h00;")
    $block.Add('    endcase');$block.Add('end');$block.Add('// END GENERATED PALETTE')
    $path=Join-Path $root 'ProjectFiles/FlappyBird/RTL/VGA/HartsMatrixBitMap.sv'
    $text=[IO.File]::ReadAllText($path)
    $text=[regex]::Replace($text,'(?s)// BEGIN GENERATED PALETTE.*?// END GENERATED PALETTE',($block -join "`r`n"))
    [IO.File]::WriteAllText($path,$text,[Text.Encoding]::ASCII)
    Write-Output "Generated pickups.mif: $depth x 4 bits, $($colors.Count) opaque colors plus transparency."
} finally {$bitmap.Dispose()}
