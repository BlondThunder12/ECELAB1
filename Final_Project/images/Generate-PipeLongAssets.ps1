param(
    [string]$Source = (Join-Path $PSScriptRoot 'pipeLong.png')
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$bitmap = [System.Drawing.Bitmap]::new((Resolve-Path -LiteralPath $Source).Path)
$preview = [System.Drawing.Bitmap]::new(50, 8)
try {
    if ($bitmap.Width -ne 50 -or $bitmap.Height -ne 8) {
        throw 'The pipe-body tile must be exactly 50 x 8 pixels.'
    }

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('-- pipeLong.png: 50 x 8, row-major, RRRGGGBB, all pixels opaque.')
    $lines.Add('-- Address = (y % 8) * 50 + x. Generated by images/Generate-PipeLongAssets.ps1.')
    $lines.Add('DEPTH = 400;')
    $lines.Add('WIDTH = 8;')
    $lines.Add('ADDRESS_RADIX = HEX;')
    $lines.Add('DATA_RADIX = HEX;')
    $lines.Add('CONTENT BEGIN')
    for ($y = 0; $y -lt 8; $y++) {
        for ($x = 0; $x -lt 50; $x++) {
            $color = $bitmap.GetPixel($x, $y)
            if ($color.A -ne 255) {
                throw 'The pipe-body tile must be fully opaque.'
            }
            $red = $color.R -shr 5
            $green = $color.G -shr 5
            $blue = $color.B -shr 6
            $value = ($red -shl 5) -bor ($green -shl 2) -bor $blue
            $lines.Add(('{0:X3}: {1:X2};' -f ($y * 50 + $x), $value))
            $preview.SetPixel($x, $y, [System.Drawing.Color]::FromArgb(
                [int][Math]::Round($red * 255 / 7),
                [int][Math]::Round($green * 255 / 7),
                [int][Math]::Round($blue * 255 / 3)))
        }
    }
    $lines.Add('END;')
    $projectRoot = Split-Path -Parent $PSScriptRoot
    $mifPath = Join-Path $projectRoot 'ProjectFiles/FlappyBird/RTL/pipeLong.mif'
    [System.IO.File]::WriteAllLines($mifPath, $lines, [System.Text.Encoding]::ASCII)
    $bitmap.Save((Join-Path $PSScriptRoot 'pipeLong.bmp'), [System.Drawing.Imaging.ImageFormat]::Bmp)
    $preview.Save((Join-Path $PSScriptRoot 'pipeLong_RGB332.png'), [System.Drawing.Imaging.ImageFormat]::Png)
    Write-Output 'Generated pipeLong.mif (400 x 8 bits), pipeLong.bmp, and pipeLong_RGB332.png.'
}
finally {
    $preview.Dispose()
    $bitmap.Dispose()
}
